"""
The GS1 Barcode Syntax Engine's messages, recognised so that the portal shows them in the user's language
(Documentation/adr/0003-gs1-rules-from-the-dictionary.md).

engine_messages.json, generated by tools/gen_engine_messages.py from the sources of the engine release written in
docker-compose.yml, holds the engine's English templates (printf style, "AI (%.*s) value is too short") and its
linters' messages ("The date contains an illegal month of the year."). recognise() turns an engine message into a
message code and parameters: engine.<CODE> with p1, p2… in the order of the template, a linter's message being a
parameter of its own, engine.lint.<CODE>. static/i18n.js holds both languages of every code; the English one is
the engine's text (catalogue_text()), so a message reads the same as before in English.
"""
import json
import os
import re

PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "engine_messages.json")
SPEC = re.compile(r"%(?:\.\*s|\.\d+s|z?u|l?d|c|s|%)")


def load(path: str = PATH) -> dict:
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)


def catalogue_text(template: str) -> str:
    """The catalogue's form of an engine template: each printf parameter becomes {p1}, {p2}…; "%%" becomes "%"."""
    count = 0

    def placeholder(match: re.Match) -> str:
        nonlocal count
        if match.group(0) == "%%":
            return "%"
        count += 1
        return f"{{p{count}}}"

    return SPEC.sub(placeholder, template)


def _pattern(template: str) -> re.Pattern:
    parts, position = [], 0
    for match in SPEC.finditer(template):
        parts.append(re.escape(template[position:match.start()]))
        spec = match.group(0)
        if spec == "%%":
            parts.append("%")
        elif spec.endswith(("u", "d")):
            parts.append(r"(-?\d+)")
        elif spec == "%c":
            parts.append("(.)")
        elif spec[1:2] == "." and spec[2:-1].isdigit():
            parts.append(f"(.{{0,{spec[2:-1]}}}?)")
        else:
            parts.append("(.*?)")
        position = match.end()
    parts.append(re.escape(template[position:]))
    return re.compile("^" + "".join(parts) + "$", re.S)


class Messages:
    """The recogniser for one table (the committed one by default)."""

    def __init__(self, data: dict | None = None):
        data = data if data is not None else load()
        self.release = data["release"]
        # the most specific template first (the most fixed text), so that a general one never hides it
        self._templates = sorted(((m["code"], _pattern(m["template"]), len(SPEC.sub("", m["template"])))
                                  for m in data["messages"]), key=lambda t: -t[2])
        self._linters = {lint["text"]: lint["code"] for lint in data["linters"]}

    def recognise(self, text: str) -> dict | None:
        """{"code": "engine.<CODE>", "params": {"p1": …}} for a message of the engine; a parameter that is itself
        one of its messages (a linter's, "engine.lint.<CODE>", or another template's) is given the same way;
        None for any other text."""
        if text in self._linters:
            return {"code": "engine.lint." + self._linters[text], "params": {}}
        for code, pattern, _ in self._templates:
            if match := pattern.match(text):
                return {"code": "engine." + code,
                        "params": {f"p{number}": self.recognise(value) or value
                                   for number, value in enumerate(match.groups(), 1)}}
        return None


_default: Messages | bool | None = None


def recognise(text: str) -> dict | None:
    """Messages().recognise(text) with the committed table, loaded once; None when the table cannot be read
    (the message is then shown as the engine wrote it)."""
    global _default
    if _default is None:
        try:
            _default = Messages()
        except (OSError, ValueError, KeyError):
            _default = False
    return _default.recognise(text) if _default else None
